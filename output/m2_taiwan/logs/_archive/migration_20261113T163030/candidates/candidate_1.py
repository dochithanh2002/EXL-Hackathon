"""M2 Taiwan card-default PD: Python migration of legacy R model `legacy_models/m2_taiwan/model.R`.

Generated by the R->Python Migration Agent (rulebook v1.1). Faithful translation (GOV-01): the protected attributes
sex and marriage, and education (a proxy), are model inputs exactly as in the R source and are flagged for validation.

Estimation reproduces R's stats::glm.fit IRLS numerical path exactly (R-EST-01, R-EST-02):
same starting values (mustart = (y + 0.5) / 2), same stopping rule
|dev - dev_old| / (|dev| + 0.1) < epsilon = 1e-8, maxit = 25, and standard errors from the QR
decomposition of the LAST iteration's weighted design (as summary.glm does). A fully converged
fit (e.g. statsmodels with tol=1e-12) matches R's coefficients to ~1e-10 but R's standard errors
only to ~1e-5, because R stops early by design.

Rules applied: R-IO-01 R-IO-02 R-IO-03 R-IDX-01 R-IDX-02 R-REC-01 R-REC-02 R-FAC-01 R-FAC-02
               R-FAC-03 R-FAC-04 R-RNG-01 R-EST-01 R-EST-02 R-PRED-01 R-PKG-01 GOV-01
"""
from __future__ import annotations

import re
import numpy as np
import pandas as pd

TARGET = "default.payment.next.month"

# Factor level sets captured from the R model (glm.final$xlevels); first level = reference (R-FAC-01/02)
FACTOR_LEVELS = {"sex": [1, 2], "education": [1, 2, 3, 4], "marriage": [1, 2, 3]}
NUMERIC_TERMS = ["limit_bal", "pay_0", "pay_2", "pay_3", "pay_5", "pay_6", "pay_amt1", "pay_amt2"]
# R model.matrix column order for: ~ limit_bal+sex+education+marriage+pay_0+pay_2+pay_3+pay_5+pay_6+pay_amt1+pay_amt2
TERMS = ["(Intercept)", "limit_bal", "sex2", "education2", "education3", "education4",
         "marriage2", "marriage3", "pay_0", "pay_2", "pay_3", "pay_5", "pay_6", "pay_amt1", "pay_amt2"]
GLM_EPSILON, GLM_MAXIT = 1e-8, 25          # stats::glm.control() defaults


def _make_names(name: str) -> str:
    """R make.names() as applied by read.csv(check.names=TRUE) (R-IO-01)."""
    out = re.sub(r"[^A-Za-z0-9._]", ".", name)
    if not re.match(r"^([A-Za-z]|\.(?![0-9]))", out):
        out = "X" + out
    return out


def load_and_preprocess(csv_path: str) -> pd.DataFrame:
    df = pd.read_csv(csv_path)
    df.columns = [_make_names(c) for c in df.columns]          # R-IO-01
    df.columns = [c.lower() for c in df.columns]                # R-IO-02
    df = df.drop(columns=["id"])                                # raw.credit$id <- NULL (R-IO-03: rows untouched)

    # R-REC-02: recodes in R order
    df.loc[df["education"].isin([0, 4, 5, 6]), "education"] = 4  # R-REC-01, R-IDX-02
    df.loc[df["marriage"] == 0, "marriage"] = 3

    # R-IDX-01: `for (i in seq(6, 11, 1))` -> 1-based positions after id was dropped
    pay_cols = list(df.columns[5:11])
    assert pay_cols == ["pay_0", "pay_2", "pay_3", "pay_4", "pay_5", "pay_6"], f"schema drift: {pay_cols}"
    for c in pay_cols:
        df.loc[df[c].isin([-2, -1, 0]), c] = 0

    return df.reset_index(drop=True)


def design_matrix(df: pd.DataFrame) -> pd.DataFrame:
    """Treatment-coded design matrix with R model.matrix names and order (R-FAC-02, R-FAC-04)."""
    X = pd.DataFrame(index=df.index)
    X["(Intercept)"] = 1.0
    X["limit_bal"] = df["limit_bal"].astype(float)
    for var, levels in FACTOR_LEVELS.items():
        unknown = set(df[var].unique()) - set(levels)
        if unknown:
            raise ValueError(f"{var}: levels {sorted(unknown)} not seen by the R model")
        for lvl in levels[1:]:
            X[f"{var}{lvl}"] = (df[var] == lvl).astype(float)
    for c in NUMERIC_TERMS[1:]:
        X[c] = df[c].astype(float)
    return X[TERMS]


class GLMResult:
    """Fitted R-equivalent GLM (plain class: no dataclass, so it loads under any import mechanism)."""

    def __init__(self, params: pd.Series, bse: pd.Series, deviance: float, iterations: int, converged: bool):
        self.params, self.bse, self.deviance = params, bse, deviance
        self.iterations, self.converged = iterations, converged


def _binomial_deviance(y: np.ndarray, mu: np.ndarray) -> float:
    return float(-2.0 * np.sum(np.where(y == 1.0, np.log(mu), np.log1p(-mu))))


def fit(train: pd.DataFrame) -> GLMResult:
    """IRLS mirroring R stats::glm.fit for binomial(logit), prior weights 1 (R-EST-01, R-EST-02).
    Rows are supplied by the caller; no sampling here (R-RNG-01)."""
    X = design_matrix(train).to_numpy(dtype=float)
    y = (train[TARGET] == 1).to_numpy(dtype=float)               # R-FAC-03: event = level '1'
    mu = (y + 0.5) / 2.0                                         # binomial()$initialize
    eta = np.log(mu / (1.0 - mu))
    dev_old = _binomial_deviance(y, mu)
    converged = False
    for it in range(1, GLM_MAXIT + 1):
        mu_eta = mu * (1.0 - mu)                                 # d mu / d eta for logit
        z = eta + (y - mu) / mu_eta                              # working response
        w = np.sqrt(mu_eta)                                      # sqrt(mu.eta^2 / variance)
        Q, R = np.linalg.qr(X * w[:, None])
        coef = np.linalg.solve(R, Q.T @ (z * w))
        eta = X @ coef
        mu = 1.0 / (1.0 + np.exp(-eta))
        dev = _binomial_deviance(y, mu)
        if abs(dev - dev_old) / (abs(dev) + 0.1) < GLM_EPSILON:
            converged = True
            break
        dev_old = dev
    # summary.glm: cov = dispersion(=1) * chol2inv(R) from the last iteration's QR
    R_inv = np.linalg.inv(R)
    cov = R_inv @ R_inv.T
    return GLMResult(params=pd.Series(coef, index=TERMS), bse=pd.Series(np.sqrt(np.diag(cov)), index=TERMS),
                     deviance=dev, iterations=it, converged=converged)


def predict(result: GLMResult, df: pd.DataFrame) -> np.ndarray:
    """predict(glm, newdata, type='response') (R-PRED-01)."""
    eta = design_matrix(df).to_numpy(dtype=float) @ result.params.to_numpy()
    return 1.0 / (1.0 + np.exp(-eta))


def coefficients(result: GLMResult) -> pd.DataFrame:
    return pd.DataFrame({"term": result.params.index, "estimate": result.params.values,
                         "std_error": result.bse.values})
