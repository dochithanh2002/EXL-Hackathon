"""M2 independent validation: discrimination, calibration, back-test, stability, specification.

Champion = the Python module generated by the Migration Agent (agent/validators/m2_taiwan/champion.py); its SHA-256 is recorded.
Outputs -> output/m2_taiwan/reports/validation/ (validation_results.json, tables, charts) + MLflow run.
Run by the Validation agent.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import statsmodels.api as sm
from scipy import stats
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.metrics import brier_score_loss, roc_curve

from agent.validators.m2_taiwan import common as c

OUT = c.M.reports / "validation"
FEATURES_ALL = ["limit_bal", "sex", "education", "marriage", "age", "pay_0", "pay_2", "pay_3", "pay_4",
                "pay_5", "pay_6"] + [f"bill_amt{i}" for i in range(1, 7)] + [f"pay_amt{i}" for i in range(1, 7)]
MODEL_VARS = ["limit_bal", "pay_0", "pay_2", "pay_3", "pay_5", "pay_6", "pay_amt1", "pay_amt2"]

# Traffic-light thresholds: agent/config/thresholds.yaml -> validation.binary_pd
_T = c.M.thresholds("validation")
RAG = {
    "auc": (_T["auc"]["green"], _T["auc"]["amber"]),      # green >= g, amber >= a, else red
    "psi": (_T["psi"]["green"], _T["psi"]["amber"]),      # green < g, amber < a, else red
    "hl_p": _T["hl_p_min"],                               # HL p-value below this = calibration concern
    "cal_gap_pp": _T["cal_gap_pp"],                       # |mean PD - observed| in percentage points
    "band_p": _T["band_test_p"],
}
_FT = c.M.thresholds("fairness")


def rag_auc(a):
    return "GREEN" if a >= RAG["auc"][0] else "AMBER" if a >= RAG["auc"][1] else "RED"


def rag_psi(p):
    return "GREEN" if p < RAG["psi"][0] else "AMBER" if p < RAG["psi"][1] else "RED"


def shifted_month(df: pd.DataFrame) -> pd.DataFrame:
    """Pseudo out-of-time: re-score each client as at Aug-2005 (one month earlier).
    Proxy outcome = delayed repayment in Sep-2005 (pay_0 >= 1). pay_6 (Mar) is unobserved -> carried."""
    s = df.copy()
    s["pay_0"], s["pay_2"], s["pay_3"], s["pay_5"] = df["pay_2"], df["pay_3"], df["pay_4"], df["pay_6"]
    s["pay_amt1"], s["pay_amt2"] = df["pay_amt2"], df["pay_amt3"]
    s["limit_bal"] = df["limit_bal"]
    s["proxy_y"] = (df["pay_0"] >= 1).astype(int)
    return s


def calibration_table(y, p, edges) -> pd.DataFrame:
    d = pd.DataFrame({"y": y, "p": p})
    d["band"] = pd.cut(d["p"], edges, labels=False) + 1
    t = d.groupby("band").agg(n=("y", "size"), defaults=("y", "sum"), mean_pd=("p", "mean"),
                              obs_rate=("y", "mean"))
    t["gap_pp"] = 100 * (t["mean_pd"] - t["obs_rate"])
    # Two-sided binomial test of observed defaults vs mean PD (back-test per grade)
    t["binom_p"] = [stats.binomtest(int(k), int(n), float(m)).pvalue for k, n, m in
                    zip(t["defaults"], t["n"], t["mean_pd"])]
    t["flag"] = np.where(t["binom_p"] < RAG["band_p"], np.where(t["gap_pp"] > 0, "over-predicts", "UNDER-predicts"), "ok")
    return t.reset_index()


def main() -> dict:
    OUT.mkdir(parents=True, exist_ok=True)
    df = c.load()
    tr, te = df[df["set"] == "train"].copy(), df[df["set"] == "test"].copy()
    m = c.fit_glm(tr)
    tr["pd"], te["pd"] = c.score(m, tr), c.score(m, te)
    y_tr, y_te = tr[c.TARGET].values, te[c.TARGET].values
    R = {"model_id": "M2", "timestamp_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
         "champion": c.champion.provenance()}

    # ---- 1. Discrimination --------------------------------------------------------------
    d_tr, d_te = c.disc(y_tr, tr["pd"]), c.disc(y_te, te["pd"])
    auc_ci = c.bootstrap_ci(y_te, te["pd"].values, lambda y, p: c.disc(y, p)["auc"])
    ks_ci = c.bootstrap_ci(y_te, te["pd"].values, c.ks, n=500)
    seeds = json.loads(c.SEED_SENSITIVITY.read_text())
    hgb_cols = FEATURES_ALL
    hgb = HistGradientBoostingClassifier(max_iter=300, learning_rate=0.05, random_state=0)
    hgb.fit(tr[hgb_cols], y_tr)
    chal = c.disc(y_te, hgb.predict_proba(te[hgb_cols])[:, 1])
    R["discrimination"] = {
        "train": d_tr, "test": d_te, "test_auc_ci95": auc_ci, "test_ks_ci95": ks_ci,
        "overfit_auc_gap": d_tr["auc"] - d_te["auc"],
        "repeated_split_auc": {k: seeds[k] for k in ("mean", "sd", "p2_5", "p97_5")},
        "challenger_gbm_test": chal, "champion_vs_challenger_auc_gap": chal["auc"] - d_te["auc"],
        "rag": rag_auc(d_te["auc"]),
    }

    # ---- 2. Calibration & back-test -------------------------------------------------------
    edges = c.quantile_edges(tr["pd"], 10)
    cal = calibration_table(y_te, te["pd"].values, edges)
    cal.to_csv(OUT / "calibration_backtest_test.csv", index=False)
    logit_p = np.log(te["pd"] / (1 - te["pd"]))
    slope_fit = sm.GLM(y_te, sm.add_constant(logit_p.values), family=sm.families.Binomial()).fit()
    citl = 100 * (te["pd"].mean() - y_te.mean())
    R["calibration"] = {
        "brier_test": float(brier_score_loss(y_te, te["pd"])),
        "brier_reference_base_rate": float(y_te.mean() * (1 - y_te.mean())),
        "mean_pd_test": float(te["pd"].mean()), "observed_rate_test": float(y_te.mean()),
        "calibration_in_the_large_pp": float(citl),
        "calibration_intercept": float(slope_fit.params[0]), "calibration_slope": float(slope_fit.params[1]),
        "hosmer_lemeshow_test": c.hosmer_lemeshow(y_te, te["pd"].values),
        "bands_flagged": int((cal["flag"] != "ok").sum()),
        "worst_band_gap_pp": float(cal["gap_pp"].abs().max()),
        "rag": "GREEN" if (abs(citl) < RAG["cal_gap_pp"] and (cal["flag"] != "ok").sum() == 0) else
               "AMBER" if abs(citl) < RAG["cal_gap_pp"] else "RED",
    }

    # ---- 3. Stability -------------------------------------------------------------------
    sh = shifted_month(te)
    sh["pd"] = c.score(m, sh)
    csi = {v: c.psi(tr[v], te[v], c.quantile_edges(tr[v], 10)) for v in MODEL_VARS}
    csi_oot = {v: c.psi(tr[v], sh[v], c.quantile_edges(tr[v], 10)) for v in MODEL_VARS}
    psi_tt, psi_oot = c.psi(tr["pd"], te["pd"], edges), c.psi(tr["pd"], sh["pd"], edges)
    d_oot = c.disc(sh["proxy_y"].values, sh["pd"].values)
    R["stability"] = {
        "psi_train_vs_test": psi_tt, "psi_train_vs_shifted_month": psi_oot,
        "csi_train_vs_test": csi, "csi_train_vs_shifted_month": csi_oot,
        "pseudo_oot": {"note": "Clients re-scored as at Aug-2005; proxy outcome = Sep-2005 repayment delay (pay_0>=1).",
                       "proxy_event_rate": float(sh["proxy_y"].mean()), "mean_pd": float(sh["pd"].mean()), **d_oot},
        "max_csi": max(max(csi.values()), max(csi_oot.values())),
        "rag": "AMBER" if (_T["stability_csi_red_capped_at_amber_if_score_psi_green"] and rag_psi(max(psi_tt, psi_oot)) == "GREEN"
                           and max(csi_oot.values()) >= RAG["psi"][1])
               else rag_psi(max(psi_tt, psi_oot)),
    }
    raw = pd.read_csv(c.M.data)
    code1 = {col: int((raw[col] == 1).sum()) for col in ["PAY_0", "PAY_2", "PAY_3", "PAY_4", "PAY_5", "PAY_6"]}
    R["data_quality"] = {
        "pay_code_1_counts": code1,
        "finding": ("Repayment-status code 1 (one-month delay) appears in PAY_0 but almost never in PAY_2-PAY_6, "
                    "so the months are coded inconsistently. pay_0 is not on the same scale as earlier months, "
                    "and the shifted-month pay_0 CSI (above the PSI action threshold) is driven by this artefact, not by population drift."),
        "education_undocumented_0_5_6": int(raw["EDUCATION"].isin([0, 5, 6]).sum()),
        "marriage_undocumented_0": int((raw["MARRIAGE"] == 0).sum()),
        "pay_undocumented_minus2_0": {col: int(raw[col].isin([-2, 0]).sum()) for col in code1},
    }

    # ---- 4. Specification tests ---------------------------------------------------------
    # (a) pay_0 linearity: replace linear pay_0 with bands {0,1,2,3+} and LR-test.
    def with_pay0_bands(d):
        X = c.design(d).drop(columns="pay_0")
        for k in (1, 2):
            X[f"pay0_{k}"] = (d["pay_0"] == k).astype(float)
        X["pay0_3p"] = (d["pay_0"] >= 3).astype(float)
        return X
    m_band = sm.GLM(y_tr.astype(float), with_pay0_bands(tr), family=sm.families.Binomial()).fit()
    lr = 2 * (m_band.llf - m.llf)
    auc_band = c.disc(y_te, m_band.predict(with_pay0_bands(te)))["auc"]
    # (b) excluded variables: does adding back age / bills / pay_4 / pay_amt3-6 help?
    full_terms = c.FINAL_TERMS + ["age", "pay_4"] + [f"bill_amt{i}" for i in range(1, 7)] + [f"pay_amt{i}" for i in range(3, 7)]
    def full_X(d):
        X = c.design(d)
        for t in full_terms[len(c.FINAL_TERMS):]:
            X[t] = d[t].astype(float)
        return X
    m_full = sm.GLM(y_tr.astype(float), full_X(tr), family=sm.families.Binomial()).fit()
    # (c) multicollinearity among numeric inputs
    from statsmodels.stats.outliers_influence import variance_inflation_factor
    Xn = sm.add_constant(tr[MODEL_VARS].astype(float))
    vif = {v: float(variance_inflation_factor(Xn.values, i)) for i, v in enumerate(Xn.columns) if v != "const"}
    R["specification"] = {
        "pay0_linearity_LR_stat": float(lr), "pay0_linearity_df": 2,
        "pay0_linearity_p": float(1 - stats.chi2.cdf(lr, 2)),
        "pay0_banded_test_auc": float(auc_band), "pay0_banded_auc_uplift": float(auc_band - d_te["auc"]),
        "dropped_vars_LR_stat": float(2 * (m_full.llf - m.llf)), "dropped_vars_df": len(full_terms) - len(c.FINAL_TERMS),
        "dropped_vars_p": float(1 - stats.chi2.cdf(2 * (m_full.llf - m.llf), len(full_terms) - len(c.FINAL_TERMS))),
        "vif": vif, "max_vif": max(vif.values()),
        "undocumented_codes": {
            "education_0_5_6_rows": int(df.merge(pd.read_csv(c.M.data)[["ID", "EDUCATION"]],
                                                 left_on="id", right_on="ID")["EDUCATION"].isin([0, 5, 6]).sum()),
            "education4_coef": float(m.params["education4"]), "education4_se": float(m.bse["education4"]),
        },
    }

    # ---- 5. Policy cut-off view ---------------------------------------------------------
    t80 = float(np.quantile(tr["pd"], _FT["approval_rate_policy"]))
    pol = {}
    for name, t in (("pd_0.50", _FT["pd_cutoff"]), ("approve_80pct", t80)):
        decline = te["pd"] >= t
        pol[name] = {"threshold": float(t), "approval_rate": float(1 - decline.mean()),
                     "defaulters_caught": float(decline[y_te == 1].mean()),
                     "good_customers_declined": float(decline[y_te == 0].mean()),
                     "bad_rate_in_approved": float(y_te[~decline.values].mean())}
    R["policy_cutoffs"] = pol

    # ---- Overall rating -----------------------------------------------------------------
    rags = [R["discrimination"]["rag"], R["calibration"]["rag"], R["stability"]["rag"]]
    R["overall_rag"] = "RED" if "RED" in rags else "AMBER" if "AMBER" in rags else "GREEN"

    charts(tr, te, sh, cal, R)
    (OUT / "validation_results.json").write_text(json.dumps(R, indent=2, default=float))
    log_mlflow(R)
    return R


def charts(tr, te, sh, cal, R) -> None:
    # ROC: train / test / pseudo-OOT
    fig, ax = plt.subplots(figsize=(5.2, 4.4), facecolor=c.SURFACE)
    for y, p, col, lab in ((tr[c.TARGET], tr["pd"], c.C1, "Train"), (te[c.TARGET], te["pd"], c.C2, "Test"),
                           (sh["proxy_y"], sh["pd"], c.C3, "Pseudo-OOT")):
        f, t, _ = roc_curve(y, p)
        a = c.disc(y, p)["auc"]
        ax.plot(f, t, color=col, lw=2, label=f"{lab}  AUC {a:.3f}")
    ax.plot([0, 1], [0, 1], color=c.GRID, lw=1, ls="--")
    c.style(ax, "ROC curves", "False positive rate", "True positive rate")
    ax.legend(frameon=False, fontsize=8, loc="lower right", labelcolor=c.INK2)
    fig.tight_layout(); fig.savefig(OUT / "roc.png", dpi=160); plt.close(fig)

    # Calibration by decile band
    fig, ax = plt.subplots(figsize=(6.4, 4.0), facecolor=c.SURFACE)
    x = cal["band"].values
    ax.bar(x - 0.2, 100 * cal["mean_pd"], width=0.38, color=c.C1, label="Mean predicted PD")
    ax.bar(x + 0.2, 100 * cal["obs_rate"], width=0.38, color=c.C2, label="Observed default rate")
    for xi, f, o in zip(x, cal["flag"], 100 * cal["obs_rate"]):
        if f != "ok":
            ax.annotate("*", (xi + 0.2, o), ha="center", va="bottom", color=c.INK, fontsize=12)
    c.style(ax, "Back-test by PD band (test set)", "PD band (train deciles, 1 = lowest risk)", "Default rate (%)")
    ax.set_xticks(x)
    ax.legend(frameon=False, fontsize=8, loc="upper left", labelcolor=c.INK2)
    note = ("* binomial test p < 0.05" if (cal["flag"] != "ok").any()
            else "No band differs significantly from its predicted PD (binomial test, 5%)")
    fig.text(0.99, 0.01, note, ha="right", va="bottom", fontsize=7, color=c.INK2)
    fig.tight_layout(rect=(0, 0.03, 1, 1)); fig.savefig(OUT / "calibration.png", dpi=160); plt.close(fig)

    # CSI per variable (test and pseudo-OOT)
    s = R["stability"]
    vars_ = list(s["csi_train_vs_test"].keys())
    fig, ax = plt.subplots(figsize=(6.4, 3.8), facecolor=c.SURFACE)
    y = np.arange(len(vars_))
    ax.barh(y + 0.2, [s["csi_train_vs_test"][v] for v in vars_], height=0.38, color=c.C1, label="Train vs test")
    ax.barh(y - 0.2, [s["csi_train_vs_shifted_month"][v] for v in vars_], height=0.38, color=c.C3, label="Train vs shifted month")
    for t, lab in ((RAG["psi"][0], f"{RAG['psi'][0]:.2f} watch"), (RAG["psi"][1], f"{RAG['psi'][1]:.2f} action")):
        ax.axvline(t, color=c.INK2, lw=1, ls=":")
        ax.text(t, len(vars_) - 0.4, lab, fontsize=7, color=c.INK2, ha="left")
    ax.set_yticks(y, vars_)
    c.style(ax, "Characteristic stability index (CSI)", "CSI", "")
    ax.grid(axis="x", color=c.GRID, linewidth=0.6); ax.grid(axis="y", visible=False)
    ax.legend(frameon=False, fontsize=8, loc="lower right", labelcolor=c.INK2)
    fig.tight_layout(); fig.savefig(OUT / "csi.png", dpi=160); plt.close(fig)


def log_mlflow(R: dict) -> None:
    import mlflow
    from agent.tools.mlflow_setup import init_tracking
    init_tracking(c.M.experiment())
    with mlflow.start_run(run_name="validation"):
        mlflow.set_tags({"model_id": "M2", "stage": "validation", "overall_rag": R["overall_rag"],
                         "champion_sha256": R["champion"]["module_sha256"]})
        flat = {
            "test_auc": R["discrimination"]["test"]["auc"], "test_gini": R["discrimination"]["test"]["gini"],
            "test_ks": R["discrimination"]["test"]["ks"], "challenger_auc": R["discrimination"]["challenger_gbm_test"]["auc"],
            "brier": R["calibration"]["brier_test"], "citl_pp": R["calibration"]["calibration_in_the_large_pp"],
            "cal_slope": R["calibration"]["calibration_slope"], "hl_p": R["calibration"]["hosmer_lemeshow_test"]["p_value"],
            "psi_test": R["stability"]["psi_train_vs_test"], "psi_oot": R["stability"]["psi_train_vs_shifted_month"],
            "oot_auc": R["stability"]["pseudo_oot"]["auc"],
        }
        mlflow.log_metrics(flat)
        mlflow.log_artifacts(str(OUT), "validation")


if __name__ == "__main__":
    r = main()
    print({k: (r[k]["rag"] if isinstance(r[k], dict) and "rag" in r[k] else None)
           for k in ("discrimination", "calibration", "stability")}, "overall:", r["overall_rag"])
