"""Migration report + human review checklist, generated from run state by `mrf package` (no LLM involved)."""
from __future__ import annotations

import json
from pathlib import Path


def _tbl(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] +
                     ["| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in r) + " |" for r in rows])


def migration_report(m, stage, out: Path):
    from agent.tools.migrate import rulebook
    from agent.tools.paths import rel
    cfg, st = m.cfg, stage.state
    rules, rb_version = rulebook()
    a = json.loads((m.mig_dir / "analysis.json").read_text())
    pl = json.loads((m.mig_dir / "plan.json").read_text())
    meta = json.loads((m.reference / "meta.json").read_text())
    its = st["iterations"]
    final = its[-1]
    # only THIS run: events since the current intake / migration stage started (earlier runs are archived)
    start = {n: min((v["ts_utc"] for v in json.loads((m.logs / n / "state.json").read_text())["stages"].values()), default="")
             for n in ("intake", "migration")}
    audit = [e for e in (json.loads(l) for l in (m.logs / "audit.jsonl").read_text().splitlines())
             if e.get("stage") in start and e["ts_utc"] >= start[e["stage"]]]
    triggered = json.loads((m.logs / "intake" / "scan.json").read_text())["triggered_rules"]
    hashes = json.loads((m.logs / "intake" / "state.json").read_text())["input_hashes"]

    md = f"""# Migration Report: {m.id} {cfg['model_name']}

**Status: AWAITING HUMAN APPROVAL** (guardrail G-09). Generated by the R→Python Migration Agent (rulebook v{rb_version}, sha256 {hashes['rulebook'][:12]}; thresholds sha256 {hashes['thresholds'][:12]}).

| | |
|---|---|
| Legacy source | `{rel(m.script)}` ({meta['r_version']}) |
| R model | `{meta['formula']}`, {meta['family']}/{meta['link']}, {len(meta['terms'])} coefficients |
| Python module | `{rel(m.module_path)}` |
| Agent | `agent/agents/migration-agent.md` (reasoning) + `agent/tools/` (deterministic checks) |
| Iterations | {len(its)} (limit {m.limits['max_repair_iterations']}, `agent/config/thresholds.yaml`) |
| Parity | **{final['verdict']}** |

## 1. Process trace
{_tbl(['UTC time', 'Event', 'Detail'], [[e['ts_utc'], e['event'], ', '.join(f'{k}={v}' for k, v in e.items() if k in ('stage', 'step', 'iteration', 'verdict', 'failure_stage', 'n_triggered', 'iterations'))] for e in audit])}

## 2. Analysis (agent, schema-validated)
{a['summary']}

**Randomness:** {a['randomness']}

{_tbl(['#', 'R code', 'What it does', 'Columns', 'Rules'], [[s['order'], f"`{s['r_code'][:90]}`", s['description'], ', '.join(s['columns']), ', '.join(s['rule_ids'])] for s in a['preprocessing']])}

**Protected attributes used by the legacy model (migrated faithfully per GOV-01):** {', '.join(a['protected_attributes_used']) or 'none'}

**Risks flagged for validation:**
""" + "\n".join(f"- {r}" for r in a["risks"]) + f"""

## 3. Plan and rule coverage (G-13)
{_tbl(['#', 'R construct', 'Python approach', 'Rules'], [[s['order'], s['r_construct'], s['python_approach'], ', '.join(s['rule_ids'])] for s in pl['steps']])}

MUST rules triggered by the static scan, all of which the plan cites: {', '.join(sorted(k for k, v in triggered.items() if v['severity'] == 'MUST'))}

## 4. Test & repair iterations
""" + "\n\n".join(
        f"### Iteration {i['iteration']}: {i['verdict']}\n"
        f"- Static guardrails: {'pass' if i['static_guardrails']['passed'] else 'FAIL'}"
        + "".join(f"\n  - {v['guardrail']}: {v['message']} (line {v['line']})" for v in i['static_guardrails']['violations'])
        + (f"\n- Run: {'ok' if i.get('run', {}).get('ok') else i.get('run', {}).get('error', '')}" if 'run' in i else "")
        + (f"\n- Failure stage: `{i['failure']['stage']}`" if i['verdict'] == 'FAIL' else "")
        + (f"\n- Change: {i['change_summary']}" if i.get('change_summary') else "")
        for i in its) + f"""

## 5. Final parity evidence
{_tbl(['Check', 'Observed', 'Tolerance', 'Pass'], [[c['check'], f"{c['value']:.3e}", f"{c['tolerance']:.0e}", '✅' if c['pass'] else '❌'] for c in final['parity']['checks']])}

## 6. Guardrails applied
- **G-01/G-02/G-03/G-04 (static, every candidate):** allowed imports only; no sklearn penalised estimators, RNG, re-splitting, `get_dummies`, shell, network, eval or file writes; interface contract; valid syntax.
- **G-05:** Python coefficient names match R's model.matrix names exactly.
- **G-06:** each candidate runs in an isolated interpreter (`python -I`) with credentials stripped from the environment and a {m.limits['exec_timeout_s']}s timeout.
- **G-07:** row identity holds: raw-row positions kept in order, and every row R used is present.
- **G-08:** at most {m.limits['max_repair_iterations']} iterations, after which the run escalates to a human.
- **G-09:** a human must approve before release.
- **G-10:** every agent work file (analysis, plan) is validated against its schema.
- **G-11:** the agent saw the schema and level sets only, never data rows.
- **G-12:** model.yaml, thresholds.yaml, rulebook, legacy script and data were hashed at intake and re-verified before packaging.
- **G-13:** the plan cites every triggered MUST rule.

## 7. Output package
`{m.module_name}.py`, `requirements.txt` (pinned), `tests/test_parity.py` (pytest regression against the frozen R reference), `reference/` (R capture), `manifest.json` (SHA-256 of every file), `HUMAN_REVIEW.md`.
"""
    (out / "MIGRATION_REPORT.md").write_text(md)

    review = f"""# Human Review: {m.id} migration

Approve in Claude Code with `/mrf:approve {m.slug}` (or `agent/bin/mrf approve {m.slug} --target migration --reviewer "<name>" --decision approve|reject --comment "..."`).

Reviewer checklist:
- [ ] Read `{m.module_name}.py`. Every R preprocessing step is present, in R order (report §2).
- [ ] Positional references were resolved to the correct column names (R-IDX-01).
- [ ] Factor reference levels and dummy names match R (`reference/meta.json` → xlevels).
- [ ] The split is imported from R, not re-randomised (R-RNG-01).
- [ ] Parity evidence (§5) is within the frozen tolerances, and `.venv/bin/python -m pytest {rel(m.model_dir)}/tests` passes.
- [ ] Risks and protected attributes (§2) are handed to independent validation. Migration does NOT fix them (GOV-01).
- [ ] Manifest hashes match the files under review.
"""
    (out / "HUMAN_REVIEW.md").write_text(review)
